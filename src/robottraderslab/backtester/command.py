import logging
from pathlib import Path

from robottraderslab.analyser import resolve_run_folder
from robottraderslab.bootstrap import (
    BotConfig,
    load_log_handlers,
    load_secrets,
    report_unavailable_notifiers,
)
from robottraderslab.exceptions import BotCriticalError, ExchangeCriticalError
from robottraderslab.reporting import timestamp_now

from .backtest_logging import RUN_LOG_FILENAME, setup_backtest_logging
from .backtest_outputs import BacktestOutputs
from .runners import require_backtest_config, run_backtest

logger = logging.getLogger(__name__)


def main(
    folder: Path,
    logfile_override: Path | None,
    console: bool,
    chart: bool,
    save: bool,
) -> None:
    """Replay the bot the folder holds over its `[backtest]` window.

    Raises:
        BotCriticalError: If the config is unusable.
        ExchangeCriticalError: If the run cannot reach what it needs.
        RuntimeError: If the run closed no trade, so there is nothing to report.
    """
    bot_config = BotConfig.from_folder(folder)
    backtest_config = require_backtest_config(bot_config)
    logging_config = backtest_config.logging
    timestamp = timestamp_now()
    run_log = resolve_run_folder(bot_config, timestamp) / RUN_LOG_FILENAME
    logfile = _logfile(
        logging_config.enable_file,
        logfile_override,
        logging_config.logfile,
        run_log if save else None,
    )

    handlers, unavailable = load_log_handlers(
        backtest_config.notifier, load_secrets(bot_config.secrets_file)
    )
    setup_backtest_logging(
        logfile=logfile,
        console_level=logging_config.console_level,
        file_level=logging_config.file_level,
        enable_console=console or logfile is None,
        custom_handlers=handlers,
    )
    report_unavailable_notifiers(unavailable)

    outputs = run_backtest(bot_config, record_log=False)
    _analyse(
        outputs,
        bot_config,
        timestamp,
        backtest_config.start_date,
        draw_chart=chart,
        save=save,
    )


def _logfile(
    enable_file: bool,
    override: Path | None,
    configured: str | None,
    run_log: Path | None,
) -> Path | None:
    if not enable_file:
        return None
    if override is not None:
        return override
    if configured is not None:
        return Path(configured)
    return run_log


def _analyse(
    outputs: BacktestOutputs,
    bot_config: BotConfig,
    timestamp: str,
    start_date: str,
    draw_chart: bool,
    save: bool,
) -> None:
    indicators_name = bot_config.strategy.strategy_class
    analyser = outputs.create_analyser(save=False)
    if analyser.closed_trades_count == 0:
        raise RuntimeError("No trades generated by the backtest, aborting analysis.")
    if save:
        analyser.save_run(bot_config, indicators_name, timestamp, start_date)
    analyser.print_performance_summary()
    if not draw_chart:
        return
    try:
        analyser.plot_candlesticks(indicators_name=indicators_name)
    except (Exception, ExchangeCriticalError, BotCriticalError):
        logger.warning("No chart drawn for `%s`", indicators_name, exc_info=True)
